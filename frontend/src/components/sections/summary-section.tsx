"use client";

import { useState } from "react";
import { FileTextIcon } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Card, CardContent, CardHeader, CardTitle } from "@/components/ui/card";
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from "@/components/ui/select";
import { Busy, ErrorNote, Section } from "@/components/section";
import { Report } from "@/components/report";
import { summarizePaper, type Paper } from "@/lib/api";

function truncate(text: string, max = 96) {
  return text.length > max ? `${text.slice(0, max).trimEnd()}...` : text;
}

export function SummarySection({
  papers,
  summaries,
  apiKeyReady,
  onResult,
}: {
  papers: Paper[];
  summaries: Record<string, string>;
  apiKeyReady: boolean;
  onResult: (paperId: string, summary: string) => void;
}) {
  const [targetIndex, setTargetIndex] = useState(0);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");

  const selectedPaper = papers[targetIndex] ?? papers[0];
  const summary = selectedPaper ? summaries[selectedPaper.paperId] : undefined;

  async function handleSummarize() {
    if (!selectedPaper) return;

    setLoading(true);
    setError("");

    try {
      const result = await summarizePaper(selectedPaper.title, selectedPaper.abstract);
      onResult(selectedPaper.paperId, result.text);
    } catch (err) {
      setError(err instanceof Error ? err.message : "Summarization failed.");
    } finally {
      setLoading(false);
    }
  }

  return (
    <Section
      step="03 / Summarization"
      title="AI structured summary"
      description="Seven factual sections generated by the Gemini LLM from the paper title and abstract only."
    >
      <div className="flex flex-col gap-3 sm:flex-row sm:items-end">
        <div className="flex flex-1 flex-col gap-1.5">
          <span className="text-sm font-medium">Paper to summarize</span>
          <Select value={String(targetIndex)} onValueChange={(value) => setTargetIndex(Number(value))}>
            <SelectTrigger className="w-full">
              <SelectValue placeholder="Select a paper" />
            </SelectTrigger>
            <SelectContent>
              {papers.map((paper, index) => (
                <SelectItem key={`${paper.paperId}-${index}`} value={String(index)}>
                  {truncate(`#${index + 1}: ${paper.title}`)}
                </SelectItem>
              ))}
            </SelectContent>
          </Select>
        </div>

        <Button size="lg" onClick={handleSummarize} disabled={loading || !apiKeyReady || !selectedPaper}>
          <FileTextIcon />
          {loading ? "Generating" : "Generate summary"}
        </Button>
      </div>

      {!apiKeyReady ? (
        <p className="text-sm text-muted-foreground">
          GEMINI_API_KEY is not configured. Add it to your .env file to enable summarization.
        </p>
      ) : null}

      {loading ? <Busy label="Generating a 7-part structured summary with the Gemini LLM" /> : null}
      {error ? <ErrorNote message={error} /> : null}

      {!loading && summary ? (
        <Card size="sm">
          <CardHeader>
            <CardTitle>{selectedPaper.title}</CardTitle>
          </CardHeader>
          <CardContent>
            <Report text={summary} />
          </CardContent>
        </Card>
      ) : null}
    </Section>
  );
}
